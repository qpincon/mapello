      <h2>30-day money-back guarantee</h2>
      <p>
        If you are not satisfied with Mapello Pro, you may request a full refund within 30 days of
        your first payment. This applies to both monthly and yearly plans.
      </p>
      <p>
        The 30-day window is counted from the date of your initial subscription payment — not from
        the start of any trial period, and not from a renewal date.
      </p>

      <h2>How to request a refund</h2>
      <p>
        Log in and go to <a href="/account">Account settings</a>. In the Subscription section you
        will see a "Request a refund" link while you are within the 30-day window. Click it and
        confirm — no email, no waiting, no back-and-forth.
      </p>
      <p>
        Refunds are submitted to our payment provider (Paddle) for review. Once approved, the
        amount is returned to your original payment method within <strong>5–10 business days</strong>,
        depending on your bank or card issuer.
      </p>

      <h2>What happens when a refund is approved</h2>
      <ul>
        <li>Your Pro access ends immediately when you submit the request.</li>
        <li>Your account reverts to the free plan (up to 3 map exports, up to 5 saved projects).</li>
        <li>Any SVG files you have already exported remain yours — they have no dependency on Mapello's servers.</li>
        <li>Your saved projects are kept and accessible on the free plan, up to the free plan limit.</li>
      </ul>

      <h2>After the 30-day window</h2>
      <p>
        Refunds are not available after the 30-day window has passed. You can still cancel your
        subscription at any time from <a href="/account">Account settings</a>; cancellation stops
        future charges and lets you keep Pro access until the end of the current billing period.
      </p>

      <h2>Renewals</h2>
      <p>
        The money-back guarantee applies only to the first payment of a new subscription. Renewal
        charges are not refundable. If you do not wish to renew, cancel before your renewal date.
      </p>

      <h2>Questions</h2>
      <p>
        If you have any questions or run into trouble with the self-service flow, please reach out
        via the <a href="/contact">contact page</a>.
      </p>
